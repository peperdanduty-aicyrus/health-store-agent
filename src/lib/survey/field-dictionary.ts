export function mapDictionaryTypeToFieldType(type: string): SurveyFieldType {
  if (type === "single_choice") return "radio";
  if (type === "multi_choice") return "multiselect";
  if (type === "textarea") return "textarea";
  if (type === "boolean") return "checkbox";
  if (type === "repeater") return "textarea";
  if (["number", "integer", "percentage"].includes(type)) return "number";
  return "text";
}
